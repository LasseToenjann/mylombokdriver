/* The booking form assembles this message; the guest sees it and presses send
   themselves. Nothing is transmitted automatically. */
window.MLD_MESSAGE_TEMPLATE = ({ name, service, date, guests, hotel, flight, extra }) => {
  const lines = [
    'Hello My Lombok Driver!',
    '',
    'I would like to book:',
    `• Service: ${service}`,
    `• Date: ${date}`,
    `• Guests: ${guests}`
  ];
  if (hotel)  lines.push(`• Hotel / pick-up: ${hotel}`);
  if (flight) lines.push(`• Flight number: ${flight}`);
  if (extra)  lines.push('', extra);
  lines.push('', `My name is ${name}.`, 'Could you confirm availability and the price? Thank you!');
  return lines.join('\n');
};
